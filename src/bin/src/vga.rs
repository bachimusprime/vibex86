/// The VGA device: register file + planar/text framebuffer.
pub struct Vga {
    pub regs: VgaRegs,
    /// 0xA0000 region memory (we read it back through the bus, so this is a
    /// thin accessor).
    pub vram: Ram,
    /// CGA 80x25 text screen buffer (char + attr per cell).
    pub text: [[(u8, u8); 80]; 25],
    /// Last rendered frame as 80x25 chars (for the terminal renderer).
    pub frame: [[(u8, u8); 80]; 25],
    pub dirty: bool,
}

impl Vga {
    pub fn new() -> Self {
        Self {
            regs: VgaRegs::new(),
            vram: Ram::new(0x20000),
            text: [[(b' ', 0x07); 80]; 25],
            frame: [[(b' ', 0x07); 80]; 25],
            dirty: true,
        }
    }

    /// Render the current text mode into `frame` from VRAM.
    pub fn render(&mut self, vram: &[u8]) {
        let base = 0xB8000 - 0xA0000; // offset of text framebuffer in VGA mem
        for row in 0..25u16 {
            for col in 0..80u16 {
                let off = (row as usize * 80 + col as usize) * 2 + base;
                let ch = vram.get(off).copied().unwrap_or(0) as u8;
                let attr = vram.get(off + 1).copied().unwrap_or(0) as u8;
                self.text[row as usize][col as usize] = (ch, attr);
            }
        }
        let changed = self.frame != self.text;
        self.frame = self.text;
        self.dirty = changed;
    }

    pub fn io_read(&mut self, port: u16) -> u8 {
        match port {
            0x3B4 | 0x3D4 => self.regs.crtc_index,
            0x3B5 | 0x3D5 => unsafe {
                *self.regs.crtc.get_unchecked(self.regs.crtc_index as usize)
            },
            0x3BA | 0x3DA => {
                // Input status 1: bit 3 = vertical retrace. Return 0 (not
                // retracing) so BIOS polls complete.
                self.regs.isr & 0x10
            }
            0x3C0 => self.regs.attr_index,
            0x3C1 => unsafe { *self.regs.attr.get_unchecked(self.regs.attr_index as usize) },
            0x3C2 => self.regs.misr,
            0x3C4 => self.regs.seq_index,
            0x3C5 => unsafe { *self.regs.seq.get_unchecked(self.regs.seq_index as usize) },
            0x3CE => self.regs.gfx_index,
            0x3CF => unsafe { *self.regs.gfx.get_unchecked(self.regs.gfx_index as usize) },
            0x3C6 => self.regs.dac_mask,
            0x3C7 => self.regs.dac_read_index,
            0x3C8 => self.regs.dac_write_index,
            0x3C9 => {
                let idx = self.regs.dac_read_index as usize;
                let v = self.regs.dac[idx][self.regs.dac_sub as usize];
                self.regs.dac_sub = (self.regs.dac_sub + 1) % 3;
                v
            }
            _ => 0xFF,
        }
    }

    pub fn io_write(&mut self, port: u16, val: u8) {
        match port {
            0x3B4 | 0x3D4 => self.regs.crtc_index = val,
            0x3B5 | 0x3D5 => unsafe {
                *self
                    .regs
                    .crtc
                    .get_unchecked_mut(self.regs.crtc_index as usize) = val;
            },
            0x3C2 => self.regs.misr = val,
            0x3C4 => self.regs.seq_index = val,
            0x3C5 => unsafe {
                *self
                    .regs
                    .seq
                    .get_unchecked_mut(self.regs.seq_index as usize) = val;
            },
            0x3CE => self.regs.gfx_index = val,
            0x3CF => unsafe {
                *self
                    .regs
                    .gfx
                    .get_unchecked_mut(self.regs.gfx_index as usize) = val;
            },
            0x3C0 => {
                if val & 0x20 != 0 {
                    return; // palette access
                }
                if self.regs.attr_flip {
                    unsafe {
                        *self
                            .regs
                            .attr
                            .get_unchecked_mut(self.regs.attr_index as usize) = val;
                    }
                } else {
                    self.regs.attr_index = val & 0x1F;
                }
                self.regs.attr_flip = !self.regs.attr_flip;
            }
            0x3C1 => {}
            0x3C6 => self.regs.dac_mask = val,
            0x3C7 => self.regs.dac_read_index = val,
            0x3C8 => {
                self.regs.dac_write_index = val;
                self.regs.dac_sub = 0;
            }
            0x3C9 => {
                let idx = self.regs.dac_write_index as usize;
                self.regs.dac[idx][self.regs.dac_sub as usize] = val >> 2;
                self.regs.dac_sub = (self.regs.dac_sub + 1) % 3;
            }
            _ => {}
        }
    }
}
