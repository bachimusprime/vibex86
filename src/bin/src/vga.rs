//! VGA adapter (MDA/CGA/EGA-compatible core) plus the real Bochs VGABIOS
//! (`VGABIOS-lgpl-latest`) loader and a CGA text-mode framebuffer renderer.

use x86_rs::mem::Ram;

pub const VGA_BIOS_IMAGE: &[u8] = include_bytes!("../../../firmware/VGABIOS-lgpl-latest");
pub const BIOS_IMAGE: &[u8] = include_bytes!("../../../firmware/BIOS-bochs-latest");

/// VGA registers.
struct VgaRegs {
    // Crtc
    crtc_index: u8,
    crtc: [u8; 0x100],
    // Misc output
    misr: u8,
    // Input status 1
    isr: u8,
    // Sequencer
    seq_index: u8,
    seq: [u8; 0x100],
    // Graphics controller
    gfx_index: u8,
    gfx: [u8; 0x100],
    // Attribute controller
    attr_index: u8,
    attr: [u8; 0x20],
    /// Attribute flip-flop (read from ISR resets it).
    attr_flip: bool,
    // Color palette (DAC)
    dac_mask: u8,
    dac_write_index: u8,
    dac_read_index: u8,
    dac_sub: u8,
    dac: [[u8; 3]; 256],
    // Current mode
    pub mode: u8,
    /// Text row/col currently visible (for the renderer).
    pub font: [[u8; 8]; 256],
}

impl Default for VgaRegs {
    fn default() -> Self {
        Self::new()
    }
}

impl VgaRegs {
    fn new() -> Self {
        let mut font = [[0u8; 8]; 256];
        // Default VGA font (the VGABIOS downloads 8x16 glyphs; we only need
        // ASCII to render BIOS screens). Approximate 8x8 characters.
        base_font(&mut font);
        Self {
            crtc_index: 0,
            crtc: [0; 0x100],
            misr: 0x63,
            isr: 0,
            seq_index: 0,
            seq: [0; 0x100],
            gfx_index: 0,
            gfx: [0; 0x100],
            attr_index: 0,
            attr: [0x00; 0x20],
            attr_flip: false,
            dac_mask: 0x3F,
            dac_write_index: 0,
            dac_read_index: 0,
            dac_sub: 0,
            dac: [[0u8; 3]; 256],
            mode: 3,
            font,
        }
    }
}

